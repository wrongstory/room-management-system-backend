import { readFileSync, writeFileSync } from 'node:fs';
const base = 'src/modules/developer-reset/';
const routes = JSON.parse(readFileSync(`${base}http-admission-routes.json`, 'utf8'));
const manifest = '// Generated by scripts/generate-http-admission-edge.mjs; edit http-admission-routes.json.\n'
  + `export const httpAdmissionRoutes = ${JSON.stringify(routes)} as const;\n`;
const source = readFileSync(`${base}http-admission.ts`, 'utf8').replaceAll('\r\n', '\n');
const outputs = {
  [`${base}http-admission-routes.ts`]: manifest,
  'supabase/functions/_shared/http-admission-routes.ts': manifest,
  'supabase/functions/_shared/http-admission.ts': '// Generated by scripts/generate-http-admission-edge.mjs; edit the source.\n'
    + source.replace('./http-admission-routes.js', './http-admission-routes.ts').replace('./operation-atomic-rpc.js', './operation-atomic-rpc.ts'),
};
for (const [path, output] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error(`HTTP admission drift: ${path}`);
  } else writeFileSync(path, output);
}
