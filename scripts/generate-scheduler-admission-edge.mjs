import { readFileSync, writeFileSync } from 'node:fs';
const path = 'supabase/functions/_shared/scheduler-admission.ts';
const output = '// Generated by scripts/generate-scheduler-admission-edge.mjs; edit the source.\n'
  + readFileSync('src/modules/developer-reset/scheduler-admission.ts', 'utf8').replaceAll('\r\n', '\n').replaceAll('./worker-admission.js', './worker-admission.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Scheduler admission source drift');
} else writeFileSync(path, output);
