import { readFile, writeFile } from 'node:fs/promises';
const source = (await readFile('src/modules/developer-reset/operation-atomic-rpc.ts', 'utf8')).replaceAll('\r\n', '\n');
const target = 'supabase/functions/_shared/operation-atomic-rpc.ts';
const expected = `// Generated by scripts/generate-operation-atomic-edge.mjs. DO NOT EDIT.\n${source}`;
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== expected) throw new Error('Atomic RPC source drift');
} else await writeFile(target, expected);
