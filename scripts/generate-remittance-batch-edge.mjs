import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const source = resolve('src/modules/payroll/payroll-remittance-batch.ts');
const target = resolve('supabase/functions/_shared/payroll-remittance-batch.ts');
const output = '// Generated by scripts/generate-remittance-batch-edge.mjs; edit the source.\n'
  + readFileSync(source, 'utf8').replaceAll('\r\n', '\n')
    .replace('"./payroll-remittance-marker.js"', '"./payroll-remittance-marker-core.ts"');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) {
    throw new Error('Remittance batch Edge copy is stale');
  }
} else {
  writeFileSync(target, output);
}
