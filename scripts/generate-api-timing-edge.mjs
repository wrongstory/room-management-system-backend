import { readFile, writeFile } from 'node:fs/promises';

const source = (await readFile('src/lib/api-timing.ts', 'utf8')).replaceAll('\r\n', '\n');
const target = 'supabase/functions/_shared/api-timing.ts';
const expected = '// Generated by scripts/generate-api-timing-edge.mjs. DO NOT EDIT.\n' + source;
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== expected) throw new Error('API timing source drift');
} else await writeFile(target, expected);
