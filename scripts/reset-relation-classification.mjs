export const RESET_RELATION_NAMES = Object.freeze(Object.values(RESET_RELATION_GROUPS).flat().sort());
if (new Set(RESET_RELATION_NAMES).size !== RESET_RELATION_NAMES.length) {
  throw new Error('RESET_CLASSIFICATION_DUPLICATE_RULE');
}
const namesSchema = z.array(z.string().regex(/^(public|private)\.[a-z][a-z0-9_]*$/).max(128)).max(1000);
const manifestFingerprint = createHash('sha256')
  .update(JSON.stringify({ version: RESET_CLASSIFICATION_VERSION, groups: RESET_RELATION_GROUPS })).digest('hex');

export function classifyResetRelations(input) {
  const parsed = namesSchema.safeParse(input);
  if (!parsed.success || new Set(parsed.data).size !== parsed.data.length) {
    throw new Error('RESET_CLASSIFICATION_INVALID_INPUT');
  }
  const observed = new Set(parsed.data);
  const expected = new Set(RESET_RELATION_NAMES);
  const missing = RESET_RELATION_NAMES.filter((name) => !observed.has(name)).length;
  const unknown = parsed.data.filter((name) => !expected.has(name)).length;
  const counts = Object.fromEntries(Object.entries(RESET_RELATION_GROUPS).map(([group, names]) =>
    [group, names.filter((name) => observed.has(name)).length]));
  return {
    version: RESET_CLASSIFICATION_VERSION,
    manifestFingerprint,
    inventoryCoverageComplete: missing === 0 && unknown === 0,
    // Coverage of table names is not row-policy, FK-order, or reset safety.
    classificationComplete: false,
    executionEnabled: false,
    missingRelationCount: missing,
    unclassifiedRelationCount: unknown,
    dispositionCounts: counts,
  };
}
