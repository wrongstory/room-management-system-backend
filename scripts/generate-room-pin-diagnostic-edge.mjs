import { readFile, writeFile } from 'node:fs/promises';
const source = (await readFile('src/lib/room-pin-diagnostic.ts', 'utf8')).replaceAll('\r\n', '\n');
const target = 'supabase/functions/_shared/room-pin-diagnostic.ts';
const expected = `// Generated by scripts/generate-room-pin-diagnostic-edge.mjs. DO NOT EDIT.\n${source}`;
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== expected) throw new Error('PIN diagnostic source drift');
} else await writeFile(target, expected);
