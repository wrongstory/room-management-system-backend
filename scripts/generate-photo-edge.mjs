import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { canonicalPhotoGzip } from './photo-gzip.mjs';

// Formatting is part of generation, so Deno's independent formatting gate cannot create drift.
const denoImage = 'denoland/deno:2.1.4@sha256:3bf75873714baa410dcf7fabaf76d806d20f0ac8a7579df11577b4ed97416e34';
function formatEdge(source) {
  let value = source;
  for (let pass = 0; pass < 4; pass++) {
    const result = spawnSync('docker', ['run', '--rm', '-i', denoImage, 'deno', 'fmt', '--ext=ts', '-'], { input: value, encoding: 'utf8', maxBuffer: 1024 * 1024 });
    if (result.status !== 0) throw new Error('Pinned Deno photo generation format failed');
    if (result.stdout === value) return value;
    value = result.stdout;
  }
  throw new Error('Photo generation formatting did not converge');
}

// 좁은 platform bridge: business/validator 원본은 src에 두며 별도 수작업 구현을 만들지 않는다.
const files = ['photo-binary', 'google-drive', 'photo-service'];
const check = process.argv.includes('--check');
const assetsOnly = process.argv.includes('--assets-only');
if (!assetsOnly) {
const contract = '// Generated from supabase/functions/_shared/photo-upload-contract.ts. DO NOT EDIT.\n' + await readFile('supabase/functions/_shared/photo-upload-contract.ts', 'utf8');
if (check) {
  if (await readFile('src/modules/photos/photo-upload-contract.ts', 'utf8') !== contract) throw new Error('Photo upload Node contract drift');
} else await writeFile('src/modules/photos/photo-upload-contract.ts', contract);
for (const name of files) {
  const source = await readFile(`src/modules/photos/${name}.ts`, 'utf8');
  const generated = formatEdge('// Generated by scripts/generate-photo-edge.mjs. DO NOT EDIT.\n' + source.replace(/(from '\.\/[a-z-]+)\.js'/g, "$1.ts'"));
  const destination = `supabase/functions/_shared/${name}.ts`;
  if (check) {
    if (await readFile(destination, 'utf8') !== generated) throw new Error(`Photo Edge generated contract drift: ${name}`);
  } else await writeFile(destination, generated);
}
}
// Exact package glue + x86 only. Importing npm directly packages both WASM variants and exceeds Edge's 20MB gate.
const packageRoot = new URL('../', import.meta.resolve('@imagemagick/magick-wasm'));
const assets = [
  ['dist/index.js', 'magick.js', '395efa92ea32ad54c1b3e1d84f2ef21f53f60e9d6f4d7f947f1b08e0a31d20b4'],
  ['dist/index.d.ts', 'magick.d.ts', '9a09774833c1c3b48d0cf363441b4ee46f5e0ad4c8f2725c104ee807a60f8a1f'],
  ['NOTICE', 'magick.NOTICE', '785f309bdde0dd22079361afdfdcc972419d985d8b4cd1ba4c3185e03b6aa485']
];
if (!check) await mkdir('supabase/functions/api/assets', { recursive: true });
for (const [source, name, hash] of assets) {
  const original = await readFile(new URL(source, packageRoot));
  if (createHash('sha256').update(original).digest('hex') !== hash) throw new Error('Pinned photo decoder source checksum mismatch');
  const target = `supabase/functions/api/assets/${name}`;
  // Canvas APIs are deliberately uncallable on Edge; preserve the upstream declarations otherwise.
  const output = name === 'magick.d.ts' ? Buffer.concat([Buffer.from('type HTMLCanvasElement = never;\ntype CanvasRenderingContext2DSettings = never;\n'), original]) : original;
  if (!check) await writeFile(target, output);
  if (!(await readFile(target)).equals(output)) throw new Error('Photo decoder generated asset drift');
}
const wrapper = '// Generated pinned @imagemagick/magick-wasm 0.0.43; license: magick.NOTICE.\n// @ts-types="./magick.d.ts"\nexport * from "./magick.js";\n';
const wrapperPath = 'supabase/functions/api/assets/magick.ts';
if (check) { if (await readFile(wrapperPath, 'utf8') !== wrapper) throw new Error('Photo decoder wrapper drift'); }
else await writeFile(wrapperPath, wrapper);
const wasm = await readFile(new URL('dist/x86/magick.wasm', packageRoot));
if (wasm.length !== 14828458 || createHash('sha256').update(wasm).digest('hex') !== '5a4ed1017eda113144c86ae839c22c610afebcfebfa22b1da18e00e98d78b0f7') throw new Error('Pinned WASM checksum mismatch');
const compressed = canonicalPhotoGzip(wasm);
if (compressed.length !== 5269861 || createHash('sha256').update(compressed).digest('hex') !== '0ec87668655bced27afa7b39764f188fe16dc947d4fb37ea10e822112867121c') throw new Error('Pinned compressed WASM checksum mismatch');
const compressedPath = 'supabase/functions/api/assets/magick.wasm.gz';
if (!check) await writeFile(compressedPath, compressed);
if (!(await readFile(compressedPath)).equals(compressed)) throw new Error('Compressed WASM asset drift');
