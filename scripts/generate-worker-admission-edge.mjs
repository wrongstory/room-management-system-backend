import { readFileSync, writeFileSync } from 'node:fs';
const path = 'supabase/functions/_shared/worker-admission.ts';
const output = '// Generated by scripts/generate-worker-admission-edge.mjs; edit the source.\n'
  + readFileSync('src/modules/developer-reset/worker-admission.ts', 'utf8').replaceAll('\r\n', '\n');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Worker admission source drift');
} else writeFileSync(path, output);
