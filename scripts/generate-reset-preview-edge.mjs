import { readFileSync, writeFileSync } from 'node:fs';
import { RESET_RELATION_GROUPS } from './reset-relation-classification.mjs';

const data = `// Generated by scripts/generate-reset-preview-edge.mjs; edit the classification source.\nexport const resetRelationGroups = {\n${Object.entries(RESET_RELATION_GROUPS).map(([group, names]) => `  ${group}: [\n${names.map(name => `    ${JSON.stringify(name)},\n`).join('')}  ],\n`).join('')}} as const;\n`;
const source = readFileSync('src/modules/developer-reset/reset-preview.ts', 'utf8').replaceAll('\r\n', '\n');
const files = {
  'src/modules/developer-reset/reset-preview-groups.ts': data,
  'supabase/functions/_shared/reset-preview-groups.ts': data,
  'supabase/functions/_shared/reset-preview.ts': `// Generated by scripts/generate-reset-preview-edge.mjs; edit the source.\n${source.replace('./reset-preview-groups.js', './reset-preview-groups.ts')}`,
};
for (const [path, output] of Object.entries(files)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Reset preview generated source drift');
  } else writeFileSync(path, output);
}
