import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { describe, expect, it } from 'vitest';
const require = createRequire(import.meta.url);
const read = path => readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
const file = 'supabase/migrations/20261025043354_operation_pin_worker_admission.sql';
const sql = read(file);
describe('incremental PIN admission source boundaries', () => {
  it.each(['v15', 'v17'])('parses migration and prepared rollback-only cases with %s, without connecting', async version => {
    for (const path of [file, 'supabase/tests/operation_pin_worker_admission.sql']) {
      expect((await require(`@pgsql/parser/${version}`).parse(read(path))).stmts.length).toBeGreaterThan(8);
    }
  });
  it('never invokes the full-resync claim and retains a strict unresolved-full-work HOLD', () => {
    expect(sql).toContain("where status in ('pending','processing','failed','operator_blocked')");
    expect(sql).toContain('OPERATION_PIN_FULL_RESYNC_HOLD');
    expect(sql).not.toContain('public.claim_room_pin_sheet_full_resync(');
    expect(sql).toContain('create unique index operation_pin_claim_once');
  });
  it('checks exact processing identity before the old idempotent settle shortcut', () => {
    for (const field of ['job.status', 'job.claim_id', 'job.lease_fence', 'job.pin_version']) {
      expect(sql.indexOf(field)).toBeLessThan(sql.indexOf('result:=public.settle_room_pin_sheet_sync'));
    }
    expect(sql).toContain("if outcome in ('succeeded','already_current') and result->>'status' in ('succeeded','superseded')");
    expect(sql).toContain("to_jsonb('UNKNOWN'::text)");
  });
  it('completes only captured terminal results and own heartbeat; never expiry or later mutable state', () => {
    const complete = sql.split('create function public.complete_operation_pin_incremental')[1];
    expect(complete).toContain("worker_context->'heartbeat'->>'status' is distinct from 'succeeded'");
    expect(complete).toContain("not in ('succeeded','already_current','SUPERSEDED_BEFORE_WRITE')");
    for (const forbidden of ['deadline_at', 'room_pin_sheet_sync_outbox', 'room_pin_sheet_sync_heartbeat']) expect(complete).not.toContain(forbidden);
  });
  it('has no dynamic dispatch, new relation, deletion, policy seed, coverage assertion or provider call', () => {
    expect(sql).not.toMatch(/\b(?:execute\s+format|create table|delete from|truncate|http_post)\b/i);
    expect(sql).not.toContain('insert into private.developer_operation_control');
    expect(sql).not.toContain('coverage');
  });
  it('copies the exact canonical helper and retains the production hosted mapping HOLD', () => {
    expect(read('supabase/functions/_shared/pin-worker-admission.ts')).toBe('// Generated by scripts/generate-worker-admission-edge.mjs; edit the source.\n'
      + read('src/modules/developer-reset/pin-worker-admission.ts').replaceAll('./worker-admission.js', './worker-admission.ts'));
    expect(read('.env.example')).toContain('PIN_OPERATION_ADMISSION_MODE=disabled');
  });
});
