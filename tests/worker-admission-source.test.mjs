import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { describe, expect, it } from 'vitest';
const require = createRequire(import.meta.url);
const read = path => readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
const file = 'supabase/migrations/20261025040854_operation_worker_admission.sql';
const sql = read(file);
describe('worker admission source boundaries', () => {
  it.each(['v15', 'v17'])('parses source and prepared rollback-only SQL with %s without connecting', async version => {
    for (const path of [file, 'supabase/tests/operation_worker_admission.sql']) {
      const parsed = await require(`@pgsql/parser/${version}`).parse(read(path));
      expect(parsed.stmts.length).toBeGreaterThanOrEqual(8);
    }
  });
  it('binds terminal proof to the immutable exact attempt, never current target status', () => {
    expect(sql).toContain('create unique index operation_notification_claim_once');
    const completion = sql.split('create function public.complete_operation_notification_deliveries')[1].split('end;')[0];
    for (const predicate of ['a.id=', 'a.target_id=', 'a.lease_version=', 'a.claim_digest=', 'r.attempt_id=a.id', 'r.completed_at is not null', 'v_terminal<>v_expected']) {
      expect(completion).toContain(predicate);
    }
    expect(completion).not.toContain('notification_delivery_targets');
    expect(completion).not.toContain('deadline_at');
    expect(completion).toContain("r.outcome in ('accepted','suppressed','endpoint_gone','payload_rejected','provider_configuration_error')");
  });
  it('keeps configuration failure fixed, typed and within one transaction', () => {
    const heartbeat = sql.split('create function public.record_operation_notification_configuration_failure')[1];
    expect(heartbeat.indexOf('acquire_developer_operation_admission')).toBeLessThan(heartbeat.indexOf('record_notification_delivery_heartbeat'));
    expect(heartbeat.indexOf('record_notification_delivery_heartbeat')).toBeLessThan(heartbeat.indexOf('complete_developer_operation_admission'));
    expect(heartbeat).not.toMatch(/\bexecute\s+format\b/i);
  });
  it('generates exactly the reviewed Node helper for Edge', () => {
    expect(read('supabase/functions/_shared/worker-admission.ts')).toBe(
      '// Generated by scripts/generate-worker-admission-edge.mjs; edit the source.\n' + read('src/modules/developer-reset/worker-admission.ts'));
  });
  it('adds no table, reset, policy seed, provider invocation or coverage-complete assertion', () => {
    expect(sql).not.toMatch(/\b(?:create table|delete from|truncate|http_post|net\.)\b/i);
    expect(sql).not.toContain('insert into private.developer_operation_control');
    expect(sql).not.toContain('coverage');
    expect(sql).not.toContain('collect_developer_reset_impact_preview');
  });
});
