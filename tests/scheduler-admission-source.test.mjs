import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { describe, expect, it } from 'vitest';
const require = createRequire(import.meta.url), read = p => readFileSync(p, 'utf8').replaceAll('\r\n','\n');
const file = 'supabase/migrations/20261025043054_operation_scheduler_admission.sql';
describe('scheduler admission SQL and generated runtime', () => {
  it.each(['v15','v17'])('parses prepared sources with %s without a DB', async version => {
    for (const path of [file,'supabase/tests/operation_scheduler_admission.sql']) {
      expect((await require(`@pgsql/parser/${version}`).parse(read(path))).stmts.length).toBeGreaterThan(3);
    }
  });
  it('matches the generated helper and keeps fixed exact command/readback boundaries', () => {
    expect(read('supabase/functions/_shared/scheduler-admission.ts')).toBe(
      '// Generated by scripts/generate-scheduler-admission-edge.mjs; edit the source.\n' +
      read('src/modules/developer-reset/scheduler-admission.ts').replaceAll('./worker-admission.js','./worker-admission.ts'));
    const sql = read(file), completion = sql.split('create function public.complete_operation_reservation_scheduler')[1];
    expect(completion).toContain("command_type='reservation.process_due_transitions.v66'");
    expect(completion).toContain("command_type='assignment.process_due_lifecycle'");
    expect(completion).toContain("h.last_request_id=v_context->>'requestId'");
    expect(completion).toContain("h.status='succeeded'");
    expect(completion).toContain("h.attempt_count>(v_context->>'heartbeatAttemptAtAcquire')::integer");
    expect(completion).not.toContain('h.last_completed_at>=');
    expect(completion).not.toContain('deadline_at');
    expect(sql).not.toMatch(/\b(create table|delete from|truncate|net\.)\b/i);
  });
});
